// Turns a recording of the real terminal (bruine's test/e2e/video-recording.test.ts, RECORD_VIDEO=1)
// into src/data/terminal.ts, the module the Demo scene draws cell by cell.
//
//   node scripts/import-terminal.mjs <terminal.json>
import { readFileSync, writeFileSync } from "node:fs";

const source = process.argv[2];
if (source === undefined) {
  console.error("usage: node scripts/import-terminal.mjs <terminal.json>");
  process.exit(2);
}
const data = JSON.parse(readFileSync(source, "utf8"));
const out = new URL("../src/data/terminal.ts", import.meta.url);
writeFileSync(
  out,
  [
    "// Generated by scripts/import-terminal.mjs from a recording of the real bruine. Do not edit.",
    "/** One run of cells with the same style: column, text, foreground, background, flags (1 bold, 2 italic, 4 dim, 8 inverse, 16 underline). */",
    "export type Span = [col: number, text: string, fg: string | null, bg: string | null, flags: number];",
    "export interface TerminalRecording {",
    "  cols: number;",
    "  rows: number;",
    "  fps: number;",
    "  /** Every distinct screen row, once. */",
    "  rowTable: Span[][];",
    "  /** For each frame, its rows as indexes into rowTable. */",
    "  frames: number[][];",
    "  /** Seconds from the start of the recording to each moment that matters. */",
    "  markers: Record<string, number>;",
    "  /** When each key of a typed text was pressed, in seconds. */",
    "  keys: Record<string, number[]>;",
    "}",
    `export const TERMINAL: TerminalRecording = ${JSON.stringify(data)};`,
    "",
  ].join("\n"),
);
console.log(`src/data/terminal.ts: ${data.frames.length} frames, ${data.rowTable.length} rows, ${(JSON.stringify(data).length / 1024).toFixed(0)} KB`);
